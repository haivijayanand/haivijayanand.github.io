    ("Mechanical engineering", "Principal stresses and Mohr's circle (Day 4), natural frequencies and mode shapes (5), rotor whirl and stability (6), buckling of columns (9)."),
    ("Civil and structural", "Shear-building modes and earthquakes (5), column and frame buckling (9), principal axes of sections (4)."),
    ("Aerospace and control", "Aircraft short-period and phugoid modes, closed-loop poles, flutter (6)."),
