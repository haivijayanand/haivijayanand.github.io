    h = f'<section id="e{e["n"]}" class="eqcard"><h2><span class="n">{e["n"]}</span>{html.escape(e["name"])}</h2>\n<div>{tags}<span class="who">{e["who"]}</span>{p1}</div>\n<div class="fx">{e["f"]}</div>\n'
    if e["sym"]: h += f'<p class="sym">{e["sym"]}</p>\n'
    h += e["idea"] + '\n'
    for t, d in e["deep"]: h += f'<details class="deep"><summary>{t}</summary><div>{d}</div></details>\n'
    for t, x in e["ex"]: h += f'<div class="eg"><b>{t}</b><span class="mono">{x}</span></div>\n'
    if e["app"]: h += f'<div class="app"><b>Where you meet it</b>{e["app"]}</div>\n'
    if e["lab"]:
        w, j = e["lab"]
        h += f'<div class="widget" data-w="{w}"></div>\n' if w else f'<div class="widget" data-w="eq"><script type="application/json">{j}</script></div>\n'
    return h + '</section>\n'

